#include "Style.h"

#include <string.h>

#define EXPAND_AS_ARRAY(id, attr1) (attr1),
static const int style_bw[] = {
	FOR_STYLE_LIST(EXPAND_AS_ARRAY)
};
#undef EXPAND_AS_ARRAY

static int used_style[NUM_STYLES];

static void Style_InitColor(int id, int r, int g, int b);

static void Style_InitColor(int id, int r, int g, int b) {
	init_color(
			id,
			(r * 1000) / 255,
			(g * 1000) / 255,
			(b * 1000) / 255
			);
}

void Style_SetDefaultTheme(void) {
	if(has_colors()) {
		use_default_colors();
	}

	memcpy(used_style, style_bw, sizeof(int) * NUM_STYLES);
}

int Style_GetAttr(StyleColor color) {
	return used_style[color];
}

void Style_SetAttr(WINDOW *win, StyleColor color) {
	wattrset(win, used_style[color]);
}

enum BasicColorId {
	BASICCOLOR_TEXT = 1,
	BASICCOLOR_SELECTED,
	BASICCOLOR_RED,
	BASICCOLOR_GREEN,
	BASICCOLOR_BLUE,
	BASICCOLOR_YELLOW,
};

void Style_SetBasicColorTheme(void) {
	Style_SetDefaultTheme();

	if(!has_colors()) {
		return;
	}

	Style_InitColor(COLOR_BLACK,  0x10, 0x10, 0x10);
	Style_InitColor(COLOR_WHITE,  0xe0, 0xe0, 0xe0);
	Style_InitColor(COLOR_RED,    0xe0, 0x60, 0x60);
	Style_InitColor(COLOR_GREEN,  0x60, 0xd0, 0x60);
	Style_InitColor(COLOR_CYAN,   0x60, 0xe0, 0xe0);
	Style_InitColor(COLOR_YELLOW, 0xe0, 0xe0, 0x80);
	Style_InitColor(COLOR_MAGENTA, 0x60, 0x60, 0x60);

	init_pair(BASICCOLOR_TEXT, COLOR_WHITE, COLOR_BLACK);
	init_pair(BASICCOLOR_SELECTED, COLOR_WHITE, COLOR_MAGENTA);
	init_pair(BASICCOLOR_RED, COLOR_RED, COLOR_BLACK);
	init_pair(BASICCOLOR_GREEN, COLOR_GREEN, COLOR_BLACK);
	init_pair(BASICCOLOR_BLUE, COLOR_CYAN, COLOR_BLACK);
	init_pair(BASICCOLOR_YELLOW, COLOR_YELLOW, COLOR_BLACK);

	used_style[STYLE_WINDOW_BG] = COLOR_PAIR(BASICCOLOR_TEXT);

	used_style[STYLE_TABLE_HEADER] = COLOR_PAIR(BASICCOLOR_TEXT) | A_REVERSE;
	used_style[STYLE_TABLE_ROW] = COLOR_PAIR(BASICCOLOR_TEXT);
	used_style[STYLE_TABLE_SELECTED] = COLOR_PAIR(BASICCOLOR_SELECTED);

	used_style[STYLE_MENUBAR_BG] = COLOR_PAIR(BASICCOLOR_TEXT);
	used_style[STYLE_MENUBAR_OFF] = COLOR_PAIR(BASICCOLOR_SELECTED);
	used_style[STYLE_MENUBAR_SELECTED] = COLOR_PAIR(BASICCOLOR_TEXT) | A_REVERSE;

	used_style[STYLE_FORM_HEADER] = COLOR_PAIR(BASICCOLOR_TEXT) | A_REVERSE;
	used_style[STYLE_FORM_LABEL] = COLOR_PAIR(BASICCOLOR_TEXT) | A_REVERSE;
	used_style[STYLE_FORM_INPUT_BG] = COLOR_PAIR(BASICCOLOR_SELECTED);
	used_style[STYLE_FORM_INPUT_CURSOR] = COLOR_PAIR(BASICCOLOR_TEXT) | A_REVERSE;

	used_style[STYLE_ERROR_MSG] = COLOR_PAIR(BASICCOLOR_RED);
	used_style[STYLE_CONFIRM_MSG] = COLOR_PAIR(BASICCOLOR_YELLOW);
	used_style[STYLE_FILTER_MSG] = COLOR_PAIR(BASICCOLOR_BLUE);

	used_style[STYLE_STATS_HEADER] = COLOR_PAIR(BASICCOLOR_TEXT) | A_REVERSE;

	used_style[STYLE_BUTTON_OFF] = COLOR_PAIR(BASICCOLOR_SELECTED);
	used_style[STYLE_BUTTON_SELECTED] = COLOR_PAIR(BASICCOLOR_TEXT) | A_REVERSE;

	used_style[STYLE_HGRAPH_VLINE] = COLOR_PAIR(BASICCOLOR_BLUE);
	used_style[STYLE_HGRAPH_BAR] = COLOR_PAIR(BASICCOLOR_GREEN) | A_REVERSE;
	used_style[STYLE_HGRAPH_LABEL] = COLOR_PAIR(BASICCOLOR_TEXT);
	used_style[STYLE_HGRAPH_NUMBER] = COLOR_PAIR(BASICCOLOR_RED) | A_BOLD;

	used_style[STYLE_BOTTOM_BAR] = COLOR_PAIR(BASICCOLOR_TEXT) | A_REVERSE;

	used_style[STYLE_SEARCH_BG] = COLOR_PAIR(BASICCOLOR_TEXT);
	used_style[STYLE_SEARCH_CURSOR] = COLOR_PAIR(BASICCOLOR_TEXT) | A_REVERSE;

	used_style[STYLE_ABOUT_TEXT] = COLOR_PAIR(BASICCOLOR_TEXT) | A_BOLD;
}

